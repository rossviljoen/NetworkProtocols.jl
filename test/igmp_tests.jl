const igmp_query = [
    0x01, 0x00, 0x5e, 0x00, 0x00, 0x01, 0xa4, 0x78, 0x06, 0xf1, 0x5b, 0x30, 0x08, 0x00, 0x46, 0xc0,
    0x00, 0x20, 0x00, 0x00, 0x40, 0x00, 0x01, 0x02, 0x3b, 0x68, 0xc0, 0xa8, 0x08, 0x06, 0xe0, 0x00,
    0x00, 0x01, 0x94, 0x04, 0x00, 0x00, 0x11, 0x64, 0xee, 0x9b, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xaa, 0xf5, 0xb9, 0x8e,
]

@testset "IGMP" begin

@testset "decode" begin
    ep = decode_ethernet(igmp_query)
    ipp = decode_ipv4(ep.payload)
    @test ipp.header.dst_ip == ip"224.0.0.1"
    @test ipp.header.protocol == IPPROTOCOL_IGMP
    igmpp = decode_igmpv2(ipp.payload)
    @test igmpp.type == IGMP_MEMBERSHIP_QUERY
    @test igmpp.max_resp_time == 100
    @test igmpp.group_address == ip"0.0.0.0"
end

end
